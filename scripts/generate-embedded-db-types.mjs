// Generates the public schema shape from actual PostgreSQL metadata, for machines without Docker.
// CI also exports Supabase CLI types against the complete local Supabase stack.
import { foundationDatabase } from '../tests/helpers/database.mjs';
import { writeFileSync } from 'node:fs';
const db = await foundationDatabase();
const { rows } = await db.query(
  `select table_name,column_name,udt_name,is_nullable,column_default,is_generated from information_schema.columns where table_schema='public' order by table_name,ordinal_position`,
);
const tables = Map.groupBy(rows, (row) => row.table_name);
const { rows: foreignKeys } = await db.query(`
  select source.relname as table_name, constraint_row.conname as "foreignKeyName",
    array(select attribute.attname from unnest(constraint_row.conkey) with ordinality key(attnum,position)
      join pg_attribute attribute on attribute.attrelid=source.oid and attribute.attnum=key.attnum order by key.position) as columns,
    target.relname as "referencedRelation",
    array(select attribute.attname from unnest(constraint_row.confkey) with ordinality key(attnum,position)
      join pg_attribute attribute on attribute.attrelid=target.oid and attribute.attnum=key.attnum order by key.position) as "referencedColumns",
    exists(select 1 from pg_constraint unique_key where unique_key.conrelid=source.oid
      and unique_key.contype in ('p','u') and unique_key.conkey=constraint_row.conkey) as "isOneToOne"
  from pg_constraint constraint_row join pg_class source on source.oid=constraint_row.conrelid
  join pg_class target on target.oid=constraint_row.confrelid join pg_namespace ns on ns.oid=source.relnamespace
  where constraint_row.contype='f' and ns.nspname='public' order by source.relname,constraint_row.conname
`);
const type = (row) =>
  (({
    uuid: 'string',
    text: 'string',
    timestamptz: 'string',
    date: 'string',
    int4: 'number',
    int8: 'number',
    bool: 'boolean',
    jsonb: 'Json',
  })[row.udt_name] ??
    (() => {
      throw new Error('Unmapped database type ' + row.udt_name);
    })()) + (row.is_nullable === 'YES' ? ' | null' : '');
let output = `// Generated by scripts/generate-embedded-db-types.mjs from applied migrations. Do not edit.\nexport type Json = string | number | boolean | null | { [key: string]: Json | undefined } | Json[];\nexport type Database = { public: { Tables: {\n`;
for (const [table, columns] of tables) {
  const relationships = foreignKeys
    .filter((row) => row.table_name === table)
    .map(({ table_name: tableName, ...relationship }) => {
      if (tableName !== table) throw new Error('Relationship table mismatch');
      return relationship;
    });
  output += `${table}: { Row: {\n${columns.map((row) => `${row.column_name}: ${type(row)};`).join('\n')}\n}; Insert: {\n${columns.map((row) => `${row.column_name}${row.column_default !== null || row.is_nullable === 'YES' || row.is_generated === 'ALWAYS' ? '?' : ''}: ${row.is_generated === 'ALWAYS' ? 'never' : type(row)};`).join('\n')}\n}; Update: {\n${columns.map((row) => `${row.column_name}?: ${row.is_generated === 'ALWAYS' ? 'never' : type(row)};`).join('\n')}\n}; Relationships: ${JSON.stringify(relationships)} };\n`;
}
const { rows: functions } = await db.query(
  `select p.proname, p.proargnames, p.pronargdefaults, array(select t.typname from unnest(p.proargtypes) with ordinality a(oid,n) join pg_type t on t.oid=a.oid order by a.n) as argtypes, r.typname as result from pg_proc p join pg_namespace n on n.oid=p.pronamespace join pg_type r on r.oid=p.prorettype where n.nspname='public' order by p.proname`,
);
const functionTypes = functions
  .map(
    (f) =>
      `${f.proname}: { Args: { ${(f.proargnames ?? []).map((name, index) => `${name}${index >= f.argtypes.length - f.pronargdefaults ? '?' : ''}: ${type({ udt_name: f.argtypes[index], is_nullable: 'NO' })}`).join('; ') || '[_ in never]: never'} }; Returns: ${type({ udt_name: f.result, is_nullable: 'NO' })} }`,
  )
  .join(';');
output += `}; Views: { [_ in never]: never }; Functions: { ${functionTypes} }; Enums: { [_ in never]: never }; CompositeTypes: { [_ in never]: never } } };\n`;
writeFileSync(new URL('../src/infrastructure/supabase/database.types.ts', import.meta.url), output);
await db.close();
